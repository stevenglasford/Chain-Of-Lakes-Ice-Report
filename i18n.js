function t(lang, key, arg) {
  const dict = I18N[lang] || I18N.en;
  const val = (dict && dict[key] != null) ? dict[key] : (I18N.en[key] ?? key);
  return (typeof val === "function") ? val(arg) : val;
}

function applyTranslations(lang) {
  document.documentElement.lang = lang;

  // RTL languages
  const rtlLangs = new Set(["ar", "aii"]);
  document.documentElement.dir = rtlLangs.has(lang) ? "rtl" : "ltr";

  const keys = Object.keys(I18N.en);
  for (const k of keys) {
    const el = document.getElementById(k);
    if (el && typeof I18N.en[k] !== "function") el.textContent = t(lang, k);
  }

  // Inputs / placeholders
  const searchInput = document.getElementById("searchInput");
  if (searchInput) searchInput.placeholder = t(lang, "t_search_ph");

  // Tooltips / titles
  const copyBtn = document.getElementById("copyLatestMarkdownBtn");
  if (copyBtn) {
    copyBtn.title = t(lang, "t_copy_markdown_title");
    copyBtn.setAttribute("aria-label", t(lang, "t_copy_markdown_title"));
  }

  // Translate date-range select options by value
  const rangeSelect = document.getElementById("mapRangeSelect");
  if (rangeSelect) {
    const labelByValue = {
      all: t(lang, "t_range_all"),
      "7d": t(lang, "t_range_7d"),
      "14d": t(lang, "t_range_14d"),
      "30d": t(lang, "t_range_30d"),
      season: t(lang, "t_range_season"),
      custom: t(lang, "t_range_custom"),
    };
    for (const opt of rangeSelect.options) {
      const v = opt.value;
      if (labelByValue[v]) opt.textContent = labelByValue[v];
    }
  }

  // Translate the "All" option inside the lake filter
  const lakeFilter = document.getElementById("lakeFilter");
  if (lakeFilter) {
    const allOpt = lakeFilter.querySelector('option[value=""]');
    if (allOpt) allOpt.textContent = t(lang, "t_all");
  }
}

// Export for module builds (optional)
if (typeof window !== "undefined") {
  window.I18N = I18N;
  window.t = t;
  window.applyTranslations = applyTranslations;
}
